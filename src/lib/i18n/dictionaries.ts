const dictionaries: Record<Locale, Dictionary> = { th, en };

export function getDictionary(locale: string | undefined | null): Dictionary {
  return dictionaries[(locale as Locale) in dictionaries ? (locale as Locale) : DEFAULT_LOCALE];
}

export function format(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k: string) => String(values[k] ?? ""));
}

/** Maps a database/RPC error message to a known, user-safe error key. */
export function errorKey(message: string | undefined | null): string {
  if (!message) return "generic";
  if (message.includes("invites_pending_email_key")) return "duplicate_invite";
  const known = Object.keys(th.errors).find((k) => message.includes(k));
  return known ?? "generic";
}
